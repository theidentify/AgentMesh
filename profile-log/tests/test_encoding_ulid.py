import pytest
from agentmesh_log import encoding, ulid
from agentmesh_log.errors import ValidationError


def test_typed_injective_and_canonical():
    values = [None, False, True, 0, 1, 0.0, -0.0, 1.0, '', '1', [], {}, [1], {'a': 1}]
    assert len({encoding.typed(v) for v in values}) == len(values)
    assert encoding.typed({'b': 2, 'a': 1}) == encoding.typed({'a': 1, 'b': 2})
    assert encoding.parse(encoding.wire(values)) == values


@pytest.mark.parametrize('data', [b'{"a":1,"a":2}', b'NaN', b'Infinity', b'1e999',
    b'"\\ud800"', b'\xff', b'{', b'9223372036854775808', b'[' * 66 + b'0' + b']' * 66,
    b' ' * (1024 * 1024 + 1), 'null', 1])
def test_strict_parse(data):
    with pytest.raises(ValidationError): encoding.parse(data)


@pytest.mark.parametrize('value', [float('nan'), {1: 'a'}, (1,), 2**63, '\ud800'])
def test_encoding_rejects(value):
    with pytest.raises(ValidationError): encoding.typed(value)


def test_structure_limits(monkeypatch):
    monkeypatch.setattr(encoding, 'MAX_VALUES', 3)
    with pytest.raises(ValidationError): encoding.typed([1, 2, 3])


def test_ulid_monotonic_and_time(monkeypatch):
    # Isolate the simulated process clock from events generated by earlier tests.
    monkeypatch.setattr(ulid, '_last', -1)
    monkeypatch.setattr(ulid.time, 'time_ns', lambda: 1700000000000000000)
    ids = [ulid.generate() for _ in range(100)]
    assert ids == sorted(set(ids))
    assert ulid.timestamp(ids[0]) == 1700000000000
    monkeypatch.setattr(ulid.time, 'time_ns', lambda: 1700000000001000000)
    assert ulid.generate() > ids[-1]
    monkeypatch.setattr(ulid.time, 'time_ns', lambda: 1600000000000000000)
    assert ulid.generate() > ids[-1]


@pytest.mark.parametrize('value', ['', '0'*25, '0'*27, '8'+'0'*25, 'Z'*26,
    '0'*25+'I', '0'*25+'O', '0'*25+'L', '0'*25+'U', '0'*25+'a', None, 1])
def test_ulid_rejections(value):
    with pytest.raises(ValidationError): ulid.parse(value)
